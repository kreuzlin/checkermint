"""Upload links for phones (brief 5.7).

While filling in a submission, the page shows a QR code with a short-lived,
signed link bound to the participant and their draft. Whoever scans it can
add photos and files to that draft without logging in, for 30 minutes and
only while the draft exists. The link carries no personal data; the page
behind it shows only the task title and the requirement labels.
"""

import segno
from django.core import signing
from django.urls import reverse
from django.utils.safestring import mark_safe

from .models import Submission

SALT = "submissions.upload-link"
LIFETIME_MINUTES = 30


class InvalidUploadLink(Exception):
    def __init__(self, message):
        super().__init__(message)
        self.message = message


def make_token(draft: Submission) -> str:
    return signing.dumps({"s": draft.pk, "u": draft.user_id}, salt=SALT, compress=True)


def upload_url(request, draft: Submission) -> str:
    path = reverse("submissions:phone_upload", kwargs={"token": make_token(draft)})
    return request.build_absolute_uri(path)


def qr_svg(url: str) -> str:
    """Inline SVG of the QR code (generated locally, no external service)."""
    svg = segno.make(url, error="m").svg_inline(
        scale=4, border=2, title="QR-Code zum Hochladen mit dem Handy"
    )
    return mark_safe(svg)  # generated by segno, contains no user input as markup


def draft_for_token(token: str) -> Submission:
    """The draft the link belongs to; raises InvalidUploadLink otherwise."""
    try:
        data = signing.loads(token, salt=SALT, max_age=LIFETIME_MINUTES * 60)
    except signing.SignatureExpired:
        raise InvalidUploadLink(
            "Dieser Link ist abgelaufen. Lass dir auf dem anderen Gerät einen "
            "neuen QR-Code zeigen."
        ) from None
    except signing.BadSignature:
        raise InvalidUploadLink("Dieser Link ist ungültig.") from None
    draft = (
        Submission.objects.filter(
            pk=data.get("s"), user_id=data.get("u"), status=Submission.Status.DRAFT
        )
        .select_related("task", "task_version")
        .first()
    )
    if draft is None:
        raise InvalidUploadLink(
            "Zu diesem Link gibt es keinen Entwurf mehr (schon eingereicht oder "
            "auf eine neue Version gewechselt)."
        )
    return draft
